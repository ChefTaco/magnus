export interface AuditEvent {
  id: string;
  action: AuditAction;
  actorId: string;
  actorType: 'user' | 'agent' | 'system';
  targetType: string;
  targetId: string;
  details: Record<string, unknown>;
  ipAddress: string | null;
  timestamp: string;
}

export type UserRole = 'ADMIN' | 'OPERATOR' | 'VIEWER';
export type SecurityPermission = 'security-fusion:read' | 'security-fusion:evidence:read';

export interface User {
  id: string;
  email: string;
  name: string;
  role: UserRole;
  active: boolean;
  lastLoginAt: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

export interface AuthTokenPayload {
  userId: string;
  email: string;
  role: UserRole;
  iat: number;
  exp: number;
}

/** Hono env type providing typed Variables across all routes and middleware. */
export type AppVariables = { Variables: { user?: AuthTokenPayload; requestId?: string; traceId?: string; spanId?: string } };
