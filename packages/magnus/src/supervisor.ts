/** Starting, stopping and restarting the project's services. */
import { existsSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { mustRun, type Io } from './io.js';
import { writeAtomic, type Component, type Project } from './project.js';
import { refreshUnit, UNIT_MARKER } from './templates.js';

export function unitDirectory(project: Project, env: NodeJS.ProcessEnv): string {
  return project.state.scope === 'system'
    ? '/etc/systemd/system'
    : join(env['XDG_CONFIG_HOME'] || join(homedir(), '.config'), 'systemd', 'user');
}

function systemctlArgs(project: Project, args: string[]): string[] {
  return project.state.scope === 'user' ? ['--user', ...args] : args;
}

function unitNames(project: Project, components: readonly Component[] = project.state.components): string[] {
  return components.map((component) => `${project.state.units[component]}.service`);
}

export async function systemctl(io: Io, project: Project, ...args: string[]): Promise<void> {
  // Its own process group: a Ctrl-C during the upgrade never kills a restart halfway.
  await mustRun(io, 'systemctl', systemctlArgs(project, args), { capture: true, detached: true });
}

/**
 * systemd needs Linux, and user units need a session bus: `sudo` or a
 * plain ssh session without lingering has none, and every systemctl call
 * would fail after the database was already migrated.
 */
export async function checkSupervisor(io: Io, supervisor: Project['state']['supervisor'], scope: Project['state']['scope']): Promise<void> {
  if (supervisor !== 'systemd') return;
  if (io.platform !== 'linux') throw new Error(`systemd units need Linux; on ${io.platform} use --supervisor none and run the processes under your own service manager.`);
  const args = scope === 'user' ? ['--user', 'show-environment'] : ['show-environment'];
  const result = await io.run('systemctl', args, { capture: true }).catch((error: unknown) => ({ code: 1, stdout: '', stderr: error instanceof Error ? error.message : String(error) }));
  if (result.code !== 0) {
    throw new Error([
      `\`systemctl ${args.join(' ')}\` failed: ${(result.stderr || result.stdout).trim().split('\n').slice(-2).join(' ') || `exit ${result.code}`}.`,
      scope === 'user'
        ? 'User units need the session bus of the account that owns the project: log in as that account (not through sudo or su), or run `loginctl enable-linger <account>` and use `machinectl shell <account>@`.'
        : 'Is systemd running on this host?',
    ].join('\n'));
  }
}

/**
 * Rewrite units generated by an older engine with the current start limit
 * and Node.js path (project copies and, for systemd, the installed ones).
 * Units the operator wrote or changed beyond recognition are left alone.
 */
export function refreshUnits(io: Io, project: Project, nodePath?: string): string[] {
  const changed: string[] = [];
  const dirs = [project.path('units'), ...(project.state.supervisor === 'systemd' ? [unitDirectory(project, io.env)] : [])];
  for (const dir of dirs) {
    for (const component of project.state.components) {
      const file = join(dir, `${project.state.units[component]}.service`);
      if (!existsSync(file)) continue;
      const content = readFileSync(file, 'utf8');
      if (!content.startsWith(UNIT_MARKER) || !content.includes(project.bin('current', component === 'server' ? 'magnus-server' : 'magnus-ui'))) continue;
      const next = refreshUnit(content, nodePath);
      if (next !== content) {
        writeAtomic(file, next, 0o644);
        changed.push(file);
      }
    }
  }
  return changed;
}

export function manualRestartHint(project: Project): string {
  if (project.state.supervisor === 'none') return `restart the processes started from ${project.path('units')}/*.service (ExecStart)`;
  return project.state.scope === 'user'
    ? `systemctl --user restart ${unitNames(project).join(' ')}`
    : `sudo systemctl restart ${unitNames(project).join(' ')}`;
}

/** Restart every component (server first, so the console reconnects to the new API). */
export async function restartServices(io: Io, project: Project): Promise<void> {
  switch (project.state.supervisor) {
    case 'systemd':
      await systemctl(io, project, 'daemon-reload');
      for (const unit of unitNames(project)) {
        // StartLimitBurst guards unattended crash loops; an operator's upgrade, revert or restore
        // restarts deliberately, so clear the counter first or a quick revert-then-restore is refused.
        await systemctl(io, project, 'reset-failed', unit);
        await systemctl(io, project, 'restart', unit);
      }
      return;
    case 'none':
      io.log(`Restart the Magnus server and console now so they run ./current: ${manualRestartHint(project)}. Waiting for them…`);
      return;
  }
}

/**
 * Stop every component. Without a supervisor the operator stops them: wait
 * until the server port stops answering (and, interactively, for a yes).
 */
export async function stopServices(io: Io, project: Project, options: { timeoutMs?: number; confirm?: boolean } = {}): Promise<void> {
  if (project.state.supervisor === 'systemd') {
    for (const unit of unitNames(project).reverse()) await systemctl(io, project, 'stop', unit);
    return;
  }
  io.log(`Stop the Magnus server and console now (the processes started from ${project.path('units')}/*.service). Waiting for port ${project.state.ports.server} to close…`);
  const deadline = io.now().getTime() + (options.timeoutMs ?? 300_000);
  for (;;) {
    const answer = await io.probe(`https://127.0.0.1:${project.state.ports.server}/api/v1/health`);
    if (answer === null) break;
    if (io.now().getTime() >= deadline) throw new Error(`The server on port ${project.state.ports.server} is still running; stop it and re-run.`);
    await io.sleep(2_000);
  }
  if (options.confirm && !await io.confirm('Are the Magnus server and console both stopped?')) {
    throw new Error('Stopped: the services were not confirmed stopped.');
  }
}

export async function enableServices(io: Io, project: Project): Promise<void> {
  if (project.state.supervisor !== 'systemd') return;
  await systemctl(io, project, 'daemon-reload');
  await systemctl(io, project, 'enable', ...unitNames(project));
}
