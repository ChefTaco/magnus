#!/usr/bin/env bash
# news-reporter — Fetch top news headlines, sanitize, and write Markdown reports
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VERBOSE=0

usage() {
  cat <<EOF
Usage: $(basename "$0") [OPTIONS]

Fetch top news headlines from NewsAPI.org, sanitize content via
prompt injection filter, and write structured Markdown reports.

Environment variables:
  NEWSAPI_KEY      Required. API key from https://newsapi.org
  OUTPUT_DIR       Output directory (default: /var/lib/magnus-skills/news-reporter)
  NEWS_COUNTRY     Country code (default: us)
  NEWS_CATEGORY    Category (default: general)
  NEWS_PAGE_SIZE   Number of articles (default: 10)

Options:
  -h, --help     Show this help message and exit
  -v             Increase verbosity (repeat for more: -vv, -vvv)

Verbosity levels:
  (default)      Article titles and report summary
  -v             Include fetch timing and API response details
  -vv            Include raw article data before filtering
  -vvv           Include full API response and filter output

Examples:
  $(basename "$0")             # Fetch default news
  $(basename "$0") -v          # Verbose fetch with timing
  NEWS_CATEGORY=technology $(basename "$0")  # Tech news
EOF
  exit 0
}

log_v1() { [[ $VERBOSE -ge 1 ]] && echo "[DEBUG] $*" >&2 || true; }
log_v2() { [[ $VERBOSE -ge 2 ]] && echo "[TRACE] $*" >&2 || true; }
log_v3() { [[ $VERBOSE -ge 3 ]] && echo "[DETAIL] $*" >&2 || true; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help) usage ;;
    -vvv) VERBOSE=3; shift ;;
    -vv) VERBOSE=2; shift ;;
    -v) VERBOSE=$((VERBOSE + 1)); shift ;;
    --) shift; break ;;
    -*) echo "Unknown option: $1" >&2; usage ;;
    *) break ;;
  esac
done

echo "=== News Reporter ==="

# ── Configuration ──
: "${NEWSAPI_KEY:?NEWSAPI_KEY is required — get one at https://newsapi.org}"
: "${OUTPUT_DIR:=/var/lib/magnus-skills/news-reporter}"
: "${NEWS_COUNTRY:=us}"
: "${NEWS_CATEGORY:=general}"
: "${NEWS_PAGE_SIZE:=10}"

# These values become URL parameters: accept only what the API defines.
[[ "${NEWS_COUNTRY}" =~ ^[a-z]{2}$ ]] || { echo "ERROR: NEWS_COUNTRY must be a two-letter country code" >&2; exit 2; }
[[ "${NEWS_CATEGORY}" =~ ^[a-z]{1,32}$ ]] || { echo "ERROR: NEWS_CATEGORY must be a lowercase word" >&2; exit 2; }
[[ "${NEWS_PAGE_SIZE}" =~ ^[0-9]{1,3}$ ]] || { echo "ERROR: NEWS_PAGE_SIZE must be a number" >&2; exit 2; }
[[ "${NEWSAPI_KEY}" =~ ^[A-Za-z0-9_-]{8,128}$ ]] || { echo "ERROR: NEWSAPI_KEY has an unexpected format" >&2; exit 2; }

NODE_NAME="$(hostname)"
DATE_STAMP="$(date +%Y-%m-%d)"
TIME_STAMP="$(date +%H%M%S)"
REPORT_DIR="${OUTPUT_DIR}/${NODE_NAME}"
REPORT_FILE="${REPORT_DIR}/news-${DATE_STAMP}-${TIME_STAMP}.md"
RAW_DIR="${REPORT_DIR}/.raw"

echo "--- Configuration ---"
echo "  Country:   ${NEWS_COUNTRY}"
echo "  Category:  ${NEWS_CATEGORY}"
echo "  Page size: ${NEWS_PAGE_SIZE}"
echo "  Output:    ${REPORT_FILE}"

# ── Ensure output directories exist ──
mkdir -p "${REPORT_DIR}" "${RAW_DIR}"

# ── Fetch headlines from NewsAPI ──
echo "--- Fetching Headlines ---"
API_URL="https://newsapi.org/v2/top-headlines?country=${NEWS_COUNTRY}&category=${NEWS_CATEGORY}&pageSize=${NEWS_PAGE_SIZE}"

# The key goes in a header read from stdin, so it is never in the process list or the URL.
HTTP_CODE=$(printf 'X-Api-Key: %s\n' "${NEWSAPI_KEY}" | curl -s --max-time 30 -H @- -o "${RAW_DIR}/response.json" -w "%{http_code}" "${API_URL}" 2>/dev/null) || {
  echo "ERROR: Failed to reach NewsAPI"
  exit 1
}

if [[ "${HTTP_CODE}" != "200" ]]; then
  echo "ERROR: NewsAPI returned HTTP ${HTTP_CODE}"
  # The error body is remote text: show only its filtered message.
  jq -r '.message // empty' "${RAW_DIR}/response.json" 2>/dev/null | "${SCRIPT_DIR}/prompt-filter.sh" || true
  exit 1
fi

TOTAL=$(jq -r '.totalResults // 0' "${RAW_DIR}/response.json")
ARTICLE_COUNT=$(jq -r '.articles | length' "${RAW_DIR}/response.json")
echo "  Total results: ${TOTAL}"
echo "  Articles fetched: ${ARTICLE_COUNT}"

if [[ "${ARTICLE_COUNT}" -eq 0 ]]; then
  echo "WARNING: No articles returned"
  exit 0
fi

# ── Build Markdown report ──
echo "--- Building Report ---"

{
  echo "# News Report — ${DATE_STAMP}"
  echo ""
  echo "> Generated by Magnus News Reporter on **${NODE_NAME}** at $(date -Iseconds)"
  echo "> Category: ${NEWS_CATEGORY} | Country: ${NEWS_COUNTRY} | Total results: ${TOTAL}"
  echo ""
  echo "---"
  echo ""
} > "${REPORT_FILE}"

# Process each article
for i in $(seq 0 $((ARTICLE_COUNT - 1))); do
  TITLE=$(jq -r ".articles[${i}].title // \"Untitled\"" "${RAW_DIR}/response.json")
  SOURCE=$(jq -r ".articles[${i}].source.name // \"Unknown\"" "${RAW_DIR}/response.json")
  AUTHOR=$(jq -r ".articles[${i}].author // \"Unknown\"" "${RAW_DIR}/response.json")
  URL=$(jq -r ".articles[${i}].url // \"\"" "${RAW_DIR}/response.json")
  PUBLISHED=$(jq -r ".articles[${i}].publishedAt // \"\"" "${RAW_DIR}/response.json")
  DESCRIPTION=$(jq -r ".articles[${i}].description // \"\"" "${RAW_DIR}/response.json")
  CONTENT=$(jq -r ".articles[${i}].content // \"\"" "${RAW_DIR}/response.json")

  # Sanitize each field through the prompt injection filter
  TITLE=$(printf '%s\n' "${TITLE}" | "${SCRIPT_DIR}/prompt-filter.sh")
  DESCRIPTION=$(printf '%s\n' "${DESCRIPTION}" | "${SCRIPT_DIR}/prompt-filter.sh")
  CONTENT=$(printf '%s\n' "${CONTENT}" | "${SCRIPT_DIR}/prompt-filter.sh")
  AUTHOR=$(printf '%s\n' "${AUTHOR}" | "${SCRIPT_DIR}/prompt-filter.sh")
  # Every remote field is filtered, not only the long ones.
  SOURCE=$(printf '%s\n' "${SOURCE}" | "${SCRIPT_DIR}/prompt-filter.sh")
  [[ "${PUBLISHED}" =~ ^[0-9TZ:.+-]{1,40}$ ]] || PUBLISHED=""
  # A link target that could close the Markdown link and carry text is dropped.
  [[ "${URL}" =~ ^https?://[^[:space:]\(\)\<\>\"]{1,2000}$ ]] || URL=""

  {
    echo "## $((i + 1)). ${TITLE}"
    echo ""
    echo "- **Source:** ${SOURCE}"
    echo "- **Author:** ${AUTHOR}"
    [[ -n "${PUBLISHED}" ]] && echo "- **Published:** ${PUBLISHED}"
    [[ -n "${URL}" ]] && echo "- **URL:** [Link](${URL})"
    echo ""
    if [[ -n "${DESCRIPTION}" ]]; then
      echo "${DESCRIPTION}"
      echo ""
    fi
    if [[ -n "${CONTENT}" && "${CONTENT}" != "${DESCRIPTION}" ]]; then
      echo "${CONTENT}"
      echo ""
    fi
    echo "---"
    echo ""
  } >> "${REPORT_FILE}"

  echo "  [$((i + 1))/${ARTICLE_COUNT}] ${TITLE:0:60}..."
done

# ── Cleanup raw files ──
rm -rf "${RAW_DIR}"

echo "--- Complete ---"
echo "Report written to: ${REPORT_FILE}"
echo "Articles processed: ${ARTICLE_COUNT}"
