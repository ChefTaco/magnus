/**
 * `magnus-agent install-service`: one-time, operator-run (root) setup that
 * moves an npm-prefix install into the versioned layout the self-upgrade
 * needs, installs the launcher and writes the systemd unit:
 *
 *   /opt/magnus-agent/.env
 *   /opt/magnus-agent/versions/<X>/node_modules/@hivemagnus/magnus-agent
 *   /opt/magnus-agent/current -> versions/<X>
 *   /opt/magnus-agent/launcher/launcher.mjs   (ExecStart)
 *
 * After this the agent upgrades itself inside that directory; it never needs
 * root for it and never calls sudo.
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { AGENT_PACKAGE, pointCurrentAt } from './self-upgrade.js';

export interface InstallServiceOptions {
  dir: string;
  unprivileged: boolean;
  user: string;
  dryRun: boolean;
  start: boolean;
  unitPath: string;
  nodePath: string;
}

export const INSTALL_SERVICE_USAGE = `Usage: sudo magnus-agent install-service [options]

Moves this install into the versioned layout used by self-upgrades, installs
the upgrade launcher and writes the systemd unit. Run it once per node.

Options:
  --dir DIR          Install directory (default: AGENT_INSTALL_DIR or /opt/magnus-agent)
  --unprivileged     Run as an ordinary account (MAGNUS_AGENT_PRIVILEGED=false)
  --user NAME        Account for --unprivileged (default magnus-agent; must exist)
  --unit PATH        Unit file (default /etc/systemd/system/magnus-agent.service)
  --no-start         Write everything, but do not restart the service
  --dry-run          Print the steps without changing anything`;

export function parseInstallServiceArgs(argv: readonly string[], env: NodeJS.ProcessEnv = process.env): InstallServiceOptions | 'help' {
  const options: InstallServiceOptions = {
    dir: env['AGENT_INSTALL_DIR'] ?? '/opt/magnus-agent', unprivileged: false, user: 'magnus-agent', dryRun: false, start: true,
    unitPath: '/etc/systemd/system/magnus-agent.service', nodePath: process.execPath,
  };
  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index]!;
    const value = () => {
      const next = argv[++index];
      if (!next || next.startsWith('--')) throw new Error(`${arg} needs a value`);
      return next;
    };
    if (arg === '--help' || arg === '-h') return 'help';
    else if (arg === '--dir') options.dir = value();
    else if (arg === '--unprivileged') options.unprivileged = true;
    else if (arg === '--user') options.user = value();
    else if (arg === '--unit') options.unitPath = value();
    else if (arg === '--no-start') options.start = false;
    else if (arg === '--dry-run') options.dryRun = true;
    else throw new Error(`unknown option ${arg}`);
  }
  options.dir = resolve(options.dir);
  return options;
}

export function renderUnit(options: Pick<InstallServiceOptions, 'dir' | 'unprivileged' | 'user' | 'nodePath'>): string {
  const { dir } = options;
  const common = [
    'Type=simple',
    `WorkingDirectory=${dir}`,
    `Environment=AGENT_INSTALL_DIR=${dir}`,
    `Environment=npm_config_cache=${join(dir, '.npm')}`,
    `EnvironmentFile=${join(dir, '.env')}`,
    `ExecStart=${options.nodePath} ${join(dir, 'launcher', 'launcher.mjs')}`,
    '# Any exit restarts: the launcher exits to hand over to a new or reverted version.',
    'Restart=always',
    'RestartSec=5',
    'StandardOutput=journal',
    'StandardError=journal',
    'UMask=0077',
    'NoNewPrivileges=true',
    'PrivateTmp=true',
  ];
  const hardening = options.unprivileged ? [
    `User=${options.user}`,
    `Group=${options.user}`,
    'Environment=MAGNUS_AGENT_PRIVILEGED=false',
    'CapabilityBoundingSet=',
    'AmbientCapabilities=',
    'PrivateDevices=true',
    'ProtectSystem=strict',
    `ReadWritePaths=${dir}`,
    'StateDirectory=magnus-agent',
    'ProtectHome=read-only',
    'ProtectKernelTunables=true',
    'ProtectKernelModules=true',
    'ProtectKernelLogs=true',
    'ProtectControlGroups=true',
    'ProtectClock=true',
    'ProtectHostname=true',
    'RestrictSUIDSGID=true',
    'RestrictRealtime=true',
    'RestrictNamespaces=true',
    'LockPersonality=true',
    'RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK',
    'SystemCallArchitectures=native',
  ] : [];
  return [
    '# Generated by `magnus-agent install-service`. The launcher runs ./current and',
    '# reverts a self-upgrade that does not report a heartbeat in time.',
    '[Unit]',
    `Description=Magnus Agent${options.unprivileged ? ' (unprivileged)' : ''}`,
    'After=network-online.target',
    'Wants=network-online.target',
    'StartLimitIntervalSec=0',
    '',
    '[Service]',
    ...common,
    ...hardening,
    '',
    '[Install]',
    'WantedBy=multi-user.target',
    '',
  ].join('\n');
}

function packageRoot(): string {
  return resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
}

function ownVersion(): string {
  return (JSON.parse(readFileSync(join(packageRoot(), 'package.json'), 'utf8')) as { version: string }).version;
}

function isSymlink(path: string): boolean {
  try { return lstatSync(path).isSymbolicLink(); } catch { return false; }
}

export async function installService(argv: readonly string[]): Promise<number> {
  let options: InstallServiceOptions | 'help';
  try { options = parseInstallServiceArgs(argv); }
  catch (error) { console.error(`magnus-agent install-service: ${(error as Error).message}`); return 2; }
  if (options === 'help') { console.log(INSTALL_SERVICE_USAGE); return 0; }
  const { dir, dryRun } = options;
  if (!dryRun && (typeof process.geteuid !== 'function' || process.geteuid() !== 0)) {
    console.error('magnus-agent install-service writes a system unit; run it as root (sudo). Use --dry-run to preview.');
    return 1;
  }
  const version = ownVersion();
  const steps: string[] = [];
  const act = (description: string, action: () => void) => {
    steps.push(description);
    if (!dryRun) action();
  };
  const target = join(dir, 'versions', version);
  const current = join(dir, 'current');
  const here = realpathSync(packageRoot());

  if (!existsSync(join(dir, '.env'))) console.warn(`warning: ${join(dir, '.env')} does not exist; create it before the service starts`);
  if (isSymlink(current)) {
    steps.push(`keep the versioned layout (./current -> ${realpathSync(current)})`);
  } else {
    const prefixModules = join(dir, 'node_modules');
    const fromPrefix = existsSync(prefixModules) && here === realpathSync(join(prefixModules, ...AGENT_PACKAGE.split('/')));
    act(`create ${target}`, () => mkdirSync(target, { recursive: true }));
    if (fromPrefix) {
      act(`move ${prefixModules} to ${join(target, 'node_modules')}`, () => renameSync(prefixModules, join(target, 'node_modules')));
      for (const file of ['package.json', 'package-lock.json']) {
        if (existsSync(join(dir, file))) act(`move ${file} into ${target}`, () => renameSync(join(dir, file), join(target, file)));
      }
    } else {
      act(`npm install ${AGENT_PACKAGE}@${version} into ${target}`, () => {
        writeFileSync(join(target, 'package.json'), `${JSON.stringify({ name: `magnus-agent-${version}`, version, private: true,
          dependencies: { [AGENT_PACKAGE]: version }, allowScripts: { 'cpu-features': true, ssh2: true } }, null, 2)}\n`);
        execFileSync('npm', ['install', '--omit=dev', '--no-audit', '--no-fund', '--loglevel=error'], { cwd: target, stdio: 'inherit' });
      });
    }
    act(`point ${current} at versions/${version}`, () => pointCurrentAt(dir, version));
  }
  // The launcher is copied from the release that runs install-service, not linked:
  // self-upgrades never replace it.
  act(`install ${join(dir, 'launcher', 'launcher.mjs')}`, () => {
    mkdirSync(join(dir, 'launcher'), { recursive: true, mode: 0o755 });
    copyFileSync(join(isSymlink(current) ? realpathSync(join(current, 'node_modules', ...AGENT_PACKAGE.split('/'))) : here, 'launcher', 'launcher.mjs'),
      join(dir, 'launcher', 'launcher.mjs'));
  });
  act(`create ${join(dir, '.npm')} and ${join(dir, 'versions')}`, () => {
    mkdirSync(join(dir, '.npm'), { recursive: true, mode: 0o700 });
    mkdirSync(join(dir, 'versions'), { recursive: true });
  });
  if (options.unprivileged) {
    const user = options.user;
    act(`give ${user} the install directory (the agent writes versions/, current and its upgrade state)`, () => {
      execFileSync('id', ['-u', user], { stdio: 'ignore' });
      execFileSync('chown', [`${user}:${user}`, dir]);
      execFileSync('chown', ['-R', `${user}:${user}`, join(dir, 'versions'), join(dir, '.npm')]);
      execFileSync('chown', ['-h', `${user}:${user}`, current]);
    });
  }
  act(`write ${options.unitPath}${existsSync(options.unitPath) ? ` (previous unit kept as ${options.unitPath}.pre-launcher)` : ''}`, () => {
    if (existsSync(options.unitPath) && !existsSync(`${options.unitPath}.pre-launcher`)) copyFileSync(options.unitPath, `${options.unitPath}.pre-launcher`);
    writeFileSync(options.unitPath, renderUnit(options), { mode: 0o644 });
  });
  const unit = options.unitPath.split('/').pop()!;
  act(`systemctl daemon-reload && systemctl enable ${unit}`, () => {
    execFileSync('systemctl', ['daemon-reload']);
    execFileSync('systemctl', ['enable', unit], { stdio: 'ignore' });
  });
  if (options.start) act(`systemctl restart ${unit}`, () => execFileSync('systemctl', ['restart', unit]));

  console.log(`${dryRun ? 'Would' : 'Done'}:\n${steps.map(step => `  - ${step}`).join('\n')}`);
  if (!dryRun) console.log(`The agent now runs ${version} through the launcher; the server can upgrade it from the Nodes page or with \`magnus-server agents upgrade\`.`);
  return 0;
}
